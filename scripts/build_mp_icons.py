#!/usr/bin/env python3
"""Builds miniprogram/styles/zx-icons.wxss from the handoff's line icons.

Each icon becomes a mask so it takes the element's text colour:

    <view class="zx-i zx-i-bell"></view>          (colour = current color)

Source: docs/design/项目UI设计总纲/icons/svg/*.svg (24 × 24, stroke 1.6,
currentColor; *-fill variants add a 20 % fill). The files embed a C2PA
manifest in <metadata>; it is dropped along with its namespace, and only
the drawing is kept.

    python3 scripts/build_mp_icons.py
"""
from __future__ import annotations

import re
import urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/design/项目UI设计总纲/icons/svg"
TARGET = ROOT / "miniprogram/styles/zx-icons.wxss"


def clean(svg: str) -> str:
    svg = re.sub(r"<metadata>.*?</metadata>", "", svg, flags=re.S)
    svg = re.sub(r'\s+xmlns:c2pa="[^"]*"', "", svg)
    assert "c2pa" not in svg.lower(), "C2PA left in icon"
    # The mask only reads alpha, so any opaque colour works.
    svg = svg.replace("currentColor", "#000")
    svg = re.sub(r'\s+width="24"\s+height="24"', "", svg)
    return re.sub(r">\s+<", "><", svg).strip()


def data_uri(svg: str) -> str:
    return "data:image/svg+xml," + urllib.parse.quote(svg, safe=" =:/;,'-.")


def main() -> None:
    icons = sorted(SOURCE.glob("*.svg"))
    lines = [
        "/* GENERATED by scripts/build_mp_icons.py — do not edit. */",
        "/* Line icons as masks: they take the element's color. */",
        "",
        ".zx-i {",
        "  display: inline-block;",
        "  flex: none;",
        "  width: 40rpx;",
        "  height: 40rpx;",
        "  background-color: currentColor;",
        "  -webkit-mask-size: 100% 100%;",
        "  -webkit-mask-repeat: no-repeat;",
        "  -webkit-mask-position: center;",
        "}",
        ".zx-i--sm { width: 32rpx; height: 32rpx; }",
        ".zx-i--lg { width: 48rpx; height: 48rpx; }",
        "",
    ]
    for path in icons:
        name = path.stem
        svg = clean(path.read_text(encoding="utf-8"))
        lines.append(f'.zx-i-{name} {{ -webkit-mask-image: url("{data_uri(svg)}"); }}')
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(icons)} icons, {TARGET.stat().st_size // 1024} KB, to {TARGET}")


if __name__ == "__main__":
    main()
