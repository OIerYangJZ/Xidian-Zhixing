const body = document.body;
const root = document.documentElement;
const header = document.querySelector('#siteHeader');
const progress = document.querySelector('.scroll-progress span');
const languageSwitch = document.querySelector('#languageSwitch');
const menuToggle = document.querySelector('#menuToggle');
const menuPanel = document.querySelector('#menuPanel');
const menuClose = document.querySelector('#menuClose');
const searchToggle = document.querySelector('#searchToggle');
const searchPanel = document.querySelector('#searchPanel');
const searchClose = document.querySelector('#searchClose');
const searchForm = document.querySelector('#searchForm');
const questionPhoto = document.querySelector('.question-photo');
const pauseMotion = document.querySelector('#pauseMotion');
const navLinks = [...document.querySelectorAll('.nav-link')];
const sections = [...document.querySelectorAll('main section[id]')];
const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

const languageCookie = document.cookie.split('; ').find((entry) => entry.startsWith('zhixing-language='));
const languageFromCookie = languageCookie?.split('=')[1];
const languageFromUrl = new URLSearchParams(window.location.search).get('lang');
let language = languageFromUrl || languageFromCookie || localStorage.getItem('xidian-language') || 'zh';
let ticking = false;

function applyLanguage(nextLanguage) {
  language = nextLanguage;
  body.dataset.lang = language;
  root.lang = language === 'zh' ? 'zh-CN' : 'en';
  localStorage.setItem('xidian-language', language);
  document.cookie = `zhixing-language=${language}; Path=/; Max-Age=31536000; SameSite=Lax`;
  window.history.replaceState(null, '', `${window.location.pathname}?lang=${language}${window.location.hash}`);
  if (window.parent !== window) {
    window.parent.postMessage({ type: 'zhixing-language-change', language }, window.location.origin);
  }
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = translations[language][element.dataset.i18n];
    if (value !== undefined) element.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const value = translations[language][element.dataset.i18nPlaceholder];
    if (value !== undefined) element.placeholder = value;
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    const value = translations[language][element.dataset.i18nAriaLabel];
    if (value !== undefined) element.setAttribute('aria-label', value);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    const value = translations[language][element.dataset.i18nAlt];
    if (value !== undefined) element.alt = value;
  });
  languageSwitch.textContent = language === 'zh' ? 'EN' : '中';
  languageSwitch.setAttribute('aria-label', translations[language]['a11y.switchLanguage']);
  const motionPaused = questionPhoto.classList.contains('is-paused');
  pauseMotion.setAttribute(
    'aria-label',
    translations[language][motionPaused ? 'a11y.resumeMotion' : 'a11y.pauseMotion'],
  );
}

function setPanel(panel, open) {
  const isMenu = panel === menuPanel;
  if (open) {
    const otherPanel = isMenu ? searchPanel : menuPanel;
    otherPanel.classList.remove('is-open');
    otherPanel.setAttribute('aria-hidden', 'true');
    if (isMenu) {
      body.classList.remove('is-search-open');
    } else {
      menuToggle.classList.remove('is-open');
      menuToggle.setAttribute('aria-expanded', 'false');
      body.classList.remove('is-menu-open');
    }
  }
  panel.classList.toggle('is-open', open);
  panel.setAttribute('aria-hidden', String(!open));
  if (isMenu) {
    menuToggle.classList.toggle('is-open', open);
    menuToggle.setAttribute('aria-expanded', String(open));
    body.classList.toggle('is-menu-open', open);
  } else {
    body.classList.toggle('is-search-open', open);
    if (open) document.querySelector('#searchInput')?.focus();
  }
}

function closePanels() {
  setPanel(menuPanel, false);
  setPanel(searchPanel, false);
}

function updateScrollState() {
  ticking = false;
  const scrollTop = window.scrollY;
  const maxScroll = Math.max(1, document.documentElement.scrollHeight - window.innerHeight);
  const ratio = Math.min(1, Math.max(0, scrollTop / maxScroll));
  const heroRatio = Math.min(1, Math.max(0, scrollTop / Math.max(1, window.innerHeight)));
  progress.style.width = `${ratio * 100}%`;
  root.style.setProperty('--scroll-ratio', heroRatio.toFixed(3));

  const current = sections.reduce(
    (candidate, section) => {
      const distance = Math.abs(section.getBoundingClientRect().top - 112);
      return distance < candidate.distance ? { id: section.id, distance } : candidate;
    },
    { id: 'home', distance: Infinity },
  );
  navLinks.forEach((link) => link.classList.toggle('is-active', link.getAttribute('href') === `#${current.id}`));

  const toneSection = sections.find((section) => {
    const rect = section.getBoundingClientRect();
    return rect.top <= 90 && rect.bottom >= 90;
  });
  header.classList.toggle('is-dark', toneSection?.dataset.tone === 'dark');
  header.classList.toggle('is-blue', toneSection?.dataset.tone === 'blue');
}

function requestScrollUpdate() {
  if (!ticking) {
    ticking = true;
    window.requestAnimationFrame(updateScrollState);
  }
}

applyLanguage(language);
updateScrollState();

languageSwitch.addEventListener('click', () => applyLanguage(language === 'zh' ? 'en' : 'zh'));
menuToggle.addEventListener('click', () => setPanel(menuPanel, !menuPanel.classList.contains('is-open')));
menuClose.addEventListener('click', () => setPanel(menuPanel, false));
searchToggle.addEventListener('click', () => setPanel(searchPanel, !searchPanel.classList.contains('is-open')));
searchClose.addEventListener('click', () => setPanel(searchPanel, false));

document
  .querySelectorAll('.menu-panel a[href^="#"]')
  .forEach((link) => link.addEventListener('click', () => setPanel(menuPanel, false)));
document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape') closePanels();
});

searchForm.addEventListener('submit', (event) => {
  event.preventDefault();
  const query = new FormData(searchForm).get('q')?.toString().trim();
  if (!query) return;
  const payload = {
    keyWord: query,
    owner: '1228415538',
    token: 'tourist',
    urlPrefix: '/aop_component/',
    lang: 'i18n_zh_CN',
  };
  const encoded = btoa(unescape(encodeURIComponent(JSON.stringify(payload))));
  window.open(
    `https://www.xidian.edu.cn/aop_views/search/modules/resultpc/soso.html?query=${encoded}`,
    '_blank',
    'noopener',
  );
});

pauseMotion.addEventListener('click', () => {
  const paused = questionPhoto.classList.toggle('is-paused');
  body.classList.toggle('is-motion-paused', paused);
  pauseMotion.textContent = paused ? '▶' : 'Ⅱ';
  pauseMotion.setAttribute('aria-label', translations[language][paused ? 'a11y.resumeMotion' : 'a11y.pauseMotion']);
});

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        revealObserver.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.12, rootMargin: '0px 0px -8% 0px' },
);

document.querySelectorAll('.reveal').forEach((element) => revealObserver.observe(element));
window.addEventListener('scroll', requestScrollUpdate, { passive: true });
window.addEventListener('resize', requestScrollUpdate);

if (reduceMotion) body.classList.add('reduce-motion');
